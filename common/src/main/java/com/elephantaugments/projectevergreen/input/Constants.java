	public static String getNamespace(String structureEntry) {
        return structureEntry.split(":")[0];
    }

    public static String getLocation(String structureEntry) {
        ArrayList<String> parts = new ArrayList<>(Arrays.asList(structureEntry.split("/")));
		return getNamespace(structureEntry) + ":" + String.join("/", parts.subList(2, parts.size()));
    }

    public static String getPath(String structureEntry) {
        return structureEntry.split(":")[1];
    }

	public static SortedSet<String> parseStructureSets() {
        return supportedStructureSets.stream()
			.filter(e -> !(Blacklist.modIDs.contains(getNamespace(e))))
			.map(Constants::getLocation)
			.collect(Collectors.toCollection(TreeSet::new));
    }

	public static SortedSet<String> parseStructures() {
		return supportedStructures.stream()
			.filter(e -> !(Blacklist.modIDs.contains(getNamespace(e)) ||
				Blacklist.structureIDs.contains(getLocation(e))))
			.map(Constants::getLocation)
			.collect(Collectors.toCollection(TreeSet::new));
    }

	public static SortedSet<String> parseStructureSetPaths() {
        return supportedStructureSets.stream()
			.filter(e -> !(Blacklist.modIDs.contains(getNamespace(e))))
			.collect(Collectors.toCollection(TreeSet::new));
    }

	public static SortedSet<String> parseStructurePaths() {
		return supportedStructures.stream()
			.filter(e -> !(Blacklist.modIDs.contains(getNamespace(e)) ||
				Blacklist.structureIDs.contains(getLocation(e))))
			.collect(Collectors.toCollection(TreeSet::new));
    }

